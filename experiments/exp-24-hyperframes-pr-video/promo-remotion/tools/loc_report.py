#!/usr/bin/env python3
"""EXP-24 Phase 2 — handwritten implementation budget report.

Implements `SALAMAT_PROMO_ARENA_TASK.md` § HARD CHANGE-SIZE BUDGET:
counts added lines of *implementation* in the experiment directory, excluding
generated artifacts, owner-supplied inputs, docs, lockfiles, vendor trees and media.

  preferred <= 1200 · soft warning > 1500 · hard stop > 2500
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
EXP = HERE.parent.parent
REPO = EXP.parent.parent

IMPLEMENTATION = (".py", ".ts", ".tsx", ".js", ".json")
EXCLUDE_NAMES = {"package-lock.json"}
EXCLUDE_DIRS = ("node_modules", "out", "generated", ".hyperframes")
EXCLUDE_ARTIFACTS = {
    # generated by the pipeline; rebuildable, not handwritten
    "EDITORIAL_STORYBOARD.json", "MEDIA_MANIFEST.json", "VOICE_MANIFEST.json",
    "MUSIC_MANIFEST.json", "MOBILE_QA.json", "OWNER_MEDIA_SHORTLIST.json",
    # owner-supplied inputs
    "SALAMAT_PROMO_ARENA_TASK.md", "SALAMAT_PROMO_SCRIPT.md", "SALAMAT_PROMO_OWNER_NOTES.md",
    # experiment docs / checkpoint reports
    "PROMO_BRIEF.md", "REVISION_LOG.md", "REDUCTION_LOG.md", "MEDIA_PROVIDER_LOG.md",
    "MOBILE_QA.md", "SALAMAT_PROMO_RESULTS.md", "RESULTS.md", "README.md", "RECOVERY.md",
    "UPSTREAM_AUDIT.md", "FIXTURE.json", "STORYBOARD.json",
}
PREFERRED, SOFT, HARD = 1200, 1500, 2500


def added_lines(path: Path) -> int:
    out = subprocess.run(["git", "diff", "--numstat", "main", "--", str(path)],
                         cwd=REPO, capture_output=True, text=True).stdout.strip()
    first = out.split("\t")[0] if out else ""
    return int(first) if first.isdigit() else 0


def main() -> int:
    rows = [(added_lines(p), p.relative_to(REPO)) for p in sorted(EXP.rglob("*"))
            if p.is_file() and p.suffix in IMPLEMENTATION and p.name not in EXCLUDE_NAMES
            and p.name not in EXCLUDE_ARTIFACTS
            and not any(part in EXCLUDE_DIRS for part in p.relative_to(EXP).parts)]
    total = sum(lines for lines, _ in rows)
    print("handwritten implementation, added lines vs main:\n")
    for lines, rel in sorted(rows, reverse=True):
        print(f"  {lines:>5}  {rel}")
    print(f"\n  {total:>5}  TOTAL")
    if total > HARD:
        verdict = f"over the HARD STOP ({HARD}) — stop implementation and reduce"
    elif total > SOFT:
        verdict = f"over the soft warning ({SOFT})"
    elif total > PREFERRED:
        verdict = f"over the preferred budget ({PREFERRED})"
    else:
        verdict = f"within the preferred budget (<= {PREFERRED})"
    print(f"  budget: {verdict}")
    return 1 if total > HARD else 0


if __name__ == "__main__":
    sys.exit(main())
